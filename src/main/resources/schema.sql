CREATE TABLE IF NOT EXISTS PARTICIPANTE (
    ID INTEGER PRIMARY KEY,
    NOME VARCHAR(255) NOT NULL,
    TELEFONE VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS JOGO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRICAO VARCHAR(255) NOT NULL,
    DATA DATE NOT NULL,
    FINALIZADO BOOLEAN NOT NULL DEFAULT FALSE,
    VENCEDOR_ID INTEGER REFERENCES PARTICIPANTE(ID),
    CHECK ((FINALIZADO = FALSE AND VENCEDOR_ID IS NULL)
        OR (FINALIZADO = TRUE AND VENCEDOR_ID IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS RESULTADOS (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JOGO_ID INTEGER NOT NULL REFERENCES JOGO(ID),
    PARTICIPANTE_ID INTEGER NOT NULL REFERENCES PARTICIPANTE(ID),
    VALOR DOUBLE PRECISION NOT NULL
);
